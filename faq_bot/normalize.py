"""Нормализация текста: общий вход для определения языка и для поиска.

Договор с остальными модулями проекта:

* :func:`normalize` — единственная «точка входа» в чистый текст;
* :func:`tokens` — разбиение нормализованного текста на слова;
* :func:`translit_to_cyrillic` — латиница → кириллица, вызывается
  осознанно, а не на каждом шаге;
* :func:`fold` — «сглаженная» форма для нечёткого поиска.

Главное правило: :func:`normalize` **не трогает** буквы ``ң``, ``ө``,
``ү``. Это самый надёжный признак кыргызского языка, и терять его до
определения языка нельзя. Сглаживание ``ң→н``, ``ө→о``, ``ү→у`` вынесено
в отдельную функцию :func:`fold`, которой пользуется поиск.

Что именно делает :func:`normalize` (обратимо документированный список):

1. NFKC-нормализация Unicode (составные «й», широкие формы, лигатуры);
2. нижний регистр;
3. ``ё`` → ``е``;
4. удаление комбинирующих значков, оставшихся после пункта 2;
5. любой символ, не являющийся буквой или цифрой, становится пробелом —
   значит, пунктуация, эмодзи, ``*`` и ``#`` исчезают (USSD-код ``*100#``
   превращается в токен ``100``, одинаково в вопросе и в базе);
6. схлопывание пробелов и обрезка по краям.
"""
from __future__ import annotations

import unicodedata

__all__ = ["normalize", "tokens", "translit_to_cyrillic", "fold"]

# ---------------------------------------------------------------------------
# Нормализация
# ---------------------------------------------------------------------------


def normalize(text: str) -> str:
    """Привести текст к единому виду, сохранив буквы ң, ө, ү.

    Пустая строка, строка из пробелов или из одних эмодзи дают ``""``.
    """
    if not text:
        return ""
    prepared = unicodedata.normalize("NFKC", text).lower()
    prepared = unicodedata.normalize("NFKC", prepared)
    prepared = prepared.replace("ё", "е")
    cleaned = [
        character
        for character in prepared
        if unicodedata.category(character) != "Mn"
    ]
    spaced = [
        character if character.isalnum() else " " for character in cleaned
    ]
    return " ".join("".join(spaced).split())


def tokens(text: str) -> list[str]:
    """Список слов нормализованного текста."""
    return normalize(text).split()


# ---------------------------------------------------------------------------
# Сглаженная форма для нечёткого поиска
# ---------------------------------------------------------------------------

#: ң→н, ө→о, ү→у плюс выброшенные ь и ъ. Последнее нужно, чтобы
#: транслитерированная латиница («proverit») сходилась с кириллицей
#: («проверить»): мягкий знак в латинице не пишут почти никогда.
_FOLD_TABLE = str.maketrans({"ң": "н", "ө": "о", "ү": "у", "ь": "", "ъ": ""})


def fold(text: str) -> str:
    """«Сглаженная» форма: ``normalize`` плюс ң→н, ө→о, ү→у, без ь и ъ.

    Нужна нечёткому поиску, где «өзгөрт» и «озгорт» обязаны совпадать.
    Для определения языка она непригодна: именно эти буквы и несут сигнал.
    """
    return normalize(text).translate(_FOLD_TABLE)


# ---------------------------------------------------------------------------
# Транслитерация латиницы в кириллицу
# ---------------------------------------------------------------------------

#: Многобуквенные соответствия, проверяются в этом порядке — от длинных
#: к коротким. «sch» отдельно от «shch»: «schet» это «счет», а не «щет».
_DIGRAPHS: tuple[tuple[str, str], ...] = (
    ("shch", "щ"),
    ("sch", "сч"),
    ("sh", "ш"),
    ("ch", "ч"),
    ("zh", "ж"),
    ("kh", "х"),
    ("ts", "ц"),
    ("ck", "к"),
    ("ya", "я"),
    ("yu", "ю"),
    ("yo", "е"),
    ("ye", "е"),
)

#: Однобуквенные соответствия. «j» → «ж» по кыргызскому обычаю
#: (jatat, jok, jana), «y» и конечное «i» разбираются отдельно.
_SINGLE: dict[str, str] = {
    # Одиночное «c» читаем как «с»: так «balance» даёт «балансе» и
    # сходится с «баланс», а не разъезжается с ним («баланке»).
    "a": "а", "b": "б", "c": "с", "d": "д", "e": "е", "f": "ф",
    "g": "г", "h": "х", "i": "и", "j": "ж", "k": "к", "l": "л",
    "m": "м", "n": "н", "o": "о", "p": "п", "q": "к", "r": "р",
    "s": "с", "t": "т", "u": "у", "v": "в", "w": "в", "x": "кс",
    "z": "з",
    # Турецкие и немецкие раскладки, которыми часто пишут кыргызский.
    "ö": "ө", "ü": "ү", "ı": "ы", "ñ": "ң", "ş": "ш", "ç": "ч",
    "ğ": "г", "é": "е", "ä": "а", "â": "а", "î": "и",
}

_LATIN_VOWELS = frozenset("aeiouöüı")


def translit_to_cyrillic(text: str) -> str:
    """Перевести латиницу в кириллицу, кириллицу оставить как есть.

    Вызывается осознанно: для определения языка и для поиска по запросу,
    набранному латиницей. Текст сначала проходит :func:`normalize`.

    Правила, из-за которых это не простая таблица:

    * ``y`` после гласной — «й» (``kanday`` → «кандай»), иначе «ы»
      (``balansymdy`` → «балансымды»);
    * ``i`` в конце слова после гласной — «й» (``ishtebei`` →
      «иштебей», ``muzei`` → «музей»), поэтому разнобой
      ``ishtebei`` / ``ishtebey`` даёт одно и то же слово;
    * мягкий знак в латинице не пишется, поэтому ``proverit`` даёт
      «проверит» — сравнивать такие формы нужно через :func:`fold`.
    """
    return " ".join(_translit_word(word) for word in tokens(text))


def _translit_word(word: str) -> str:
    """Транслитерация одного слова."""
    result: list[str] = []
    index = 0
    last = len(word) - 1
    while index < len(word):
        digraph = _match_digraph(word, index)
        if digraph is not None:
            source, target = digraph
            result.append(target)
            index += len(source)
            continue
        character = word[index]
        previous = word[index - 1] if index else ""
        if character == "y":
            after_vowel = previous in _LATIN_VOWELS
            result.append("й" if after_vowel else "ы")
        elif character == "i" and index == last and previous in "aeou":
            result.append("й")
        else:
            result.append(_SINGLE.get(character, character))
        index += 1
    return "".join(result)


def _match_digraph(word: str, index: int) -> tuple[str, str] | None:
    """Найти многобуквенное соответствие, начинающееся с позиции index."""
    for source, target in _DIGRAPHS:
        if word.startswith(source, index):
            return source, target
    return None
