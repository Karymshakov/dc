def is_stopword(term: tuple[str, ...] | str) -> bool:
    """Служебное ли слово. Для латиницы проверяются все варианты записи."""
    variants = (term,) if isinstance(term, str) else term
    return any(variant in STOPWORDS for variant in variants)


def content_terms(text: str) -> list[tuple[str, ...]]:
    """Термины запроса без служебных слов."""
    return [term for term in query_terms(text) if not is_stopword(term)]


