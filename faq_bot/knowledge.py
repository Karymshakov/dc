@dataclass(frozen=True)
class Field:
    """Один индексируемый кусок темы.

    Тема индексируется не одним длинным документом, а набором коротких:
    вопрос ru, вопрос ky, каждое ключевое слово, ответы. Косинус короткого
    запроса с коротким полем осмыслен, с длинной склейкой — нет.
    """

    faq_id: int
    text: str
    weight: float
    kind: str


#: Веса полей. Ответ длинный и общий по лексике, поэтому слабее вопроса.
FIELD_WEIGHTS: dict[str, float] = {
    "question": 1.0,
    "keyword": 1.0,
    "answer": 0.55,
}


def load_faq(path: Path | None = None,
             learned: dict[int, tuple[str, ...]] | None = None,
             ) -> tuple[FaqEntry, ...]:
    """Читает faq.json и прикрепляет к каждой теме её ключевые слова.

    `learned` подменяет слой выученных фраз: так CRM проверяет новую
    фразу на копии базы, не трогая рабочую.
    """
    source = Path(path) if path is not None else config.FAQ_PATH
    raw = json.loads(source.read_text(encoding="utf-8"))
    extra = LEARNED if learned is None else learned
    entries = [
        FaqEntry(
            id=int(item["id"]),
            question_ru=str(item.get("question_ru", "")),
            question_ky=str(item.get("question_ky", "")),
            answer_ru=str(item.get("answer_ru", "")),
            answer_ky=str(item.get("answer_ky", "")),
            keywords=tuple(KEYWORDS.get(int(item["id"]), ()))
                     + tuple(extra.get(int(item["id"]), ())),
        )
        for item in raw
    ]
    entries.sort(key=lambda entry: entry.id)
    return tuple(entries)


@lru_cache(maxsize=1)
def default_faq() -> tuple[FaqEntry, ...]:
    """База из config.FAQ_PATH, прочитанная один раз на процесс."""
    return load_faq()


def build_fields(entries: tuple[FaqEntry, ...]) -> tuple[Field, ...]:
    """Разворачивает темы в плоский список индексируемых полей."""
    fields: list[Field] = []
    for entry in entries:
        for text in (entry.question_ru, entry.question_ky):
            if text.strip():
                fields.append(Field(entry.id, content_text(text, expand_latin=False),
                                    FIELD_WEIGHTS["question"], "question"))
        for keyword in entry.keywords:
            if keyword.strip():
                fields.append(Field(entry.id, content_text(keyword, expand_latin=False),
                                    FIELD_WEIGHTS["keyword"], "keyword"))
        for text in (entry.answer_ru, entry.answer_ky):
            if text.strip():
                fields.append(Field(entry.id, content_text(text, expand_latin=False),
                                    FIELD_WEIGHTS["answer"], "answer"))
    return tuple(field for field in fields if field.text)


def missing_keywords(entries: tuple[FaqEntry, ...]) -> list[int]:
    """ID тем, оставшихся без слоя синонимов: защита от забытой темы."""
    return [entry.id for entry in entries if not entry.keywords]
