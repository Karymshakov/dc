#: Живое тестирование нашло второй источник ложных совпадений после
#: служебного скелета — ОБЩИЙ КОРЕНЬ ДЕЙСТВИЯ. Вопрос про самого бота
#: «как ты работаешь» попадал в тему «не работает интернет», а «купить
#: симку» — в «купить гигабайты». Такие слова есть в базе, поэтому
#: словарный гейт их пропускает, и редки по IDF, поэтому выглядят
#: специфичными. Интента они при этом не задают: «подключить» бывает
#: у роуминга, тарифа и доп. интернета; «купить» — у SIM, гигабайтов
#: и пакета; «деньги» — у баланса, перевода, пополнения, подписок
#: и детализации сразу.
#:
#: Это НЕ стоп-слова: похожесть по ним считается по-прежнему, и короткий
#: вопрос «не работает» остаётся ближе к теме 3, чем к теме 10. Они просто
#: не считаются ПОДТВЕРЖДЕНИЕМ темы: тема, которую не подтверждает ни одно
#: различающее слово запроса, получает штраф (см. ranking.Ranker.rank).
#:
#: Правило наполнения, чтобы список не превратился в затычку под примеры:
#: корень попадает сюда, только если он (а) встречается в базе или в слое
#: синонимов и (б) принадлежит нескольким темам с разным интентом. Слово,
#: опознающее тему («баланс», «роуминг», «кошумча», «симка», «детализация»),
#: сюда попасть не может — это проверяется тестом.
GENERIC_PREFIXES: tuple[str, ...] = (
    "работ", "куп", "покуп", "подключ", "включ", "отключ", "получ",
    "провер", "узна", "стои", "сдела", "нужн", "нов",
    "деньг", "денег", "акча",
    "иште", "сатып", "текшер",
)

#: Отдельные формы, для которых префикс оказался бы слишком жадным:
#: «цен» проглотил бы «колл центр», «биле» — «билет», «кош» — «кошумча».
GENERIC_WORDS: frozenset[str] = frozenset("""
цена цены сом сомго сомду
личный личном кабинет кабинете кабинеттен кабинеттеги жеке
билем билсем билгим билуу
""".split())


def is_generic(term: tuple[str, ...] | str) -> bool:
    """Общий ли корень. Для латиницы проверяются все варианты записи."""
    variants = (term,) if isinstance(term, str) else term
    return any(variant in GENERIC_WORDS
               or variant.startswith(GENERIC_PREFIXES)
               for variant in variants)


def distinctive_terms(text: str) -> list[tuple[str, ...]]:
    """Слова запроса, которыми вообще можно различать темы.

    Из терминов запроса выброшены служебные слова и общие корни. То, что
    осталось, и есть содержание вопроса: «как купить симку» -> «симку».
    Пустой список означает, что вопрос не содержит ни одного слова,
    способного выбрать тему, — такой вопрос честнее не относить ни к одной.
    """
    return [term for term in content_terms(text) if not is_generic(term)]


def content_text(text: str, expand_latin: bool = True) -> str:
    """Свёрнутый текст без служебных слов.

    Если после чистки не осталось ничего (вопрос состоял из одних
    служебных слов), возвращается пустая строка: поиску нечего искать,
    и честный ответ — «тема не найдена».
    """
    if expand_latin:
        terms = content_terms(text)
        return " ".join(" ".join(term) for term in terms)
    return " ".join(word for word in fold(text, expand_latin=False).split()
                    if word not in STOPWORDS)


# --- Загрузка базы ---------------------------------------------------------


@dataclass(frozen=True)
class Field:
    """Один индексируемый кусок темы.

    Тема индексируется не одним длинным документом, а набором коротких:
    вопрос ru, вопрос ky, каждое ключевое слово, ответы. Косинус короткого
    запроса с коротким полем осмыслен, с длинной склейкой — нет.
    """

    faq_id: int
    text: str
    weight: float
    kind: str


#: Веса полей. Ответ длинный и общий по лексике, поэтому слабее вопроса.
FIELD_WEIGHTS: dict[str, float] = {
    "question": 1.0,
    "keyword": 1.0,
    "answer": 0.55,
}


def load_faq(path: Path | None = None) -> tuple[FaqEntry, ...]:
    """Читает faq.json и прикрепляет к каждой теме её ключевые слова."""
    source = Path(path) if path is not None else config.FAQ_PATH
    raw = json.loads(source.read_text(encoding="utf-8"))
    entries = [
        FaqEntry(
            id=int(item["id"]),
            question_ru=str(item.get("question_ru", "")),
            question_ky=str(item.get("question_ky", "")),
            answer_ru=str(item.get("answer_ru", "")),
            answer_ky=str(item.get("answer_ky", "")),
            keywords=tuple(KEYWORDS.get(int(item["id"]), ())),
        )
        for item in raw
    ]
    entries.sort(key=lambda entry: entry.id)
    return tuple(entries)


@lru_cache(maxsize=1)
def default_faq() -> tuple[FaqEntry, ...]:
    """База из config.FAQ_PATH, прочитанная один раз на процесс."""
    return load_faq()


def build_fields(entries: tuple[FaqEntry, ...]) -> tuple[Field, ...]:
    """Разворачивает темы в плоский список индексируемых полей."""
    fields: list[Field] = []
    for entry in entries:
        for text in (entry.question_ru, entry.question_ky):
            if text.strip():
                fields.append(Field(entry.id, content_text(text, expand_latin=False),
                                    FIELD_WEIGHTS["question"], "question"))
        for keyword in entry.keywords:
            if keyword.strip():
                fields.append(Field(entry.id, content_text(keyword, expand_latin=False),
                                    FIELD_WEIGHTS["keyword"], "keyword"))
        for text in (entry.answer_ru, entry.answer_ky):
            if text.strip():
                fields.append(Field(entry.id, content_text(text, expand_latin=False),
                                    FIELD_WEIGHTS["answer"], "answer"))
    return tuple(field for field in fields if field.text)


def missing_keywords(entries: tuple[FaqEntry, ...]) -> list[int]:
    """ID тем, оставшихся без слоя синонимов: защита от забытой темы."""
    return [entry.id for entry in entries if not entry.keywords]
