#: Корни ДЕЙСТВИЙ: слова, называющие операцию, а не вещь.
#:
#: Третий по счёту источник ложных совпадений, найденный живым тестом,
#: и первый, которого не лечит ни один из двух прежних гейтов:
#: ДЕЙСТВИЕ ОДНОЙ ТЕМЫ ПЛЮС ОБЪЕКТ ДРУГОЙ.
#:
#:     «сменить номер»        -> тема 5 «Как сменить тариф?» (0.63)
#:     «восстановить тариф»   -> тема 6 «Как восстановить SIM?» (0.74)
#:     «заблокировать тариф»  -> тема 13 «Как заблокировать SIM?» (0.71)
#:
#: Во всех трёх случаях глагол принадлежит теме законно и один в базе
#: встречается: «сменить» есть только у темы 5, «восстановить» только
#: у темы 6. Поэтому в GENERIC_PREFIXES («корень, принадлежащий нескольким
#: темам с разным интентом») им места нет — занести «смен» туда значит
#: отнять подтверждение у законного «хочу сменить тариф».
#:
#: Разница между законным и ложным срабатыванием не в самом глаголе,
#: а в том, СОВПАДАЕТ ЛИ ОБЪЕКТ. Смены номера оператор не предлагает
#: вовсе: «сменить» живёт у темы 5, «номер» — у тем 6, 12, 13, и ни одна
#: тема не содержит обоих слов. Запрос описывает операцию, которой в базе
#: нет, и честный ответ на него — отказ с тремя кнопками, а не ближайший
#: по буквам глагол. Правило целиком в search_fuzzy.supported_topics.
#:
#: Это НЕ продолжение HOMONYM_CONTEXT, и смешивать их нельзя. Там признак
#: бытового значения — спутник, которого в базе оператора нет вовсе
#: («футбол» рядом с «эсеп»): отсутствие спутника в базе и есть
#: доказательство, что речь не про оператора, поэтому ограничение
#: «спутника нет в базе» там обязательно и остаётся. Здесь оба слова свои,
#: оператор говорит и «сменить», и «номер»; чужой только их СОЧЕТАНИЕ,
#: и о нём известно из самой базы, а не из списка. Списком задана ровно
#: одна вещь — какие слова являются операциями; пары вычисляются из базы.
#:
#: Правило наполнения, машинно проверяемое тестом: корень попадает сюда,
#: только если (а) он встречается в базе или в слое синонимов — иначе он
#: не подтверждает ни одной темы и в правиле не участвует, то есть запись
#: была бы мёртвой; (б) он называет операцию, а не предмет: подставляется
#: в «как <корень> тариф / номер / симку» и остаётся осмысленным хотя бы
#: с двумя из них. Опознаватель-существительное («баланс», «тариф»,
#: «номер», «симка», «роуминг», «детализация») сюда попасть не может —
#: это проверяется тестом.
#:
#: Намеренно НЕ действия:
#:   «потерял», «жоголду», «уурдалган», «списали», «снимают» — это не
#:   операция, которую абонент просит выполнить, а событие, которое с ним
#:   случилось, и именно оно опознаёт тему («потерял симку» -> 6);
#:   «байланыш» — в кыргызском это и «связь» (темы 3, 4), и основа глагола
#:   «байланышуу» (тема 14), то есть объект и действие в одном корне;
#:   «алуу» («получить/взять») — вспомогательный глагол, который стоит
#:   у тем 6, 7 и 15 сразу и никакой операции не называет; его русская
#:   пара «получ» по той же причине лежит в GENERIC_PREFIXES.
ACTION_PREFIXES: tuple[str, ...] = (
    # сменить / поменять / перейти — тема 5
    "смен", "помен", "измен", "перейт", "переход", "алмашт", "озгор",
    # восстановить / заменить — тема 6
    "восстанов", "замен", "келтир",
    # заблокировать — тема 13
    "заблокир", "блокир", "боготт",
    # настроить — тема 10
    "настро", "жондо",
    # пополнить / положить / оплатить — тема 11
    # «толукт», а не «толук»: кыргызское «толук» само по себе значит
    # «полный» («толук маалымат» — полная информация), это не операция.
    "пополн", "полож", "закин", "кину", "внес", "оплат", "заплат",
    "толукт",
    # перевести / скинуть — тема 9
    "перевес", "перевод", "перекин", "скин", "отправ", "подел",
    "котор", "жибер",
    # отписаться / остановить подписку — тема 8
    # («очур» — кыргызское «отключить», он в GENERIC_PREFIXES)
    "отпис", "убра", "токтот",
    # докупить / продлить — тема 7
    "докуп", "добав", "продл",
    # связаться с оператором — тема 14
    # «обрати», а не «обрат»: «обратно» — наречие, а не операция.
    "позва", "связа", "поговор", "обрати", "соедин", "суйлош", "кайрыл",
)

#: Отдельные формы действий, для которых префикс оказался бы слишком
#: жадным. «кош» проглотил бы «кошумча» — опознаватель темы 7, а «сал» —
#: половину кыргызских слов. Записаны в свёрнутом виде (ө→о, ү→у).
#:
#: Здесь только те формы, которые база называет сама: правило сверяет
#: роли по общей ОСНОВЕ (search_fuzzy.shares_stem), а у кыргызских форм
#: одного глагола общая основа часто короче пяти букв («кошуп» и «кошуу»
#: делят четыре). Такая форма не нашла бы своей темы, то есть в правиле
#: не участвовала бы вовсе, и запись была бы мёртвой. Проверяется тестом.
#:
#: «Салам» в этот список НЕ входит, хотя формально это «салуу» в первом
#: лице. Это же слово — кыргызское приветствие, и живой абонент начинает
#: с него примерно каждую вторую реплику. Пока «салам» считался действием,
#: вопрос «салам алейкум, менин интернетим иштебей жатат» терял тему 3:
#: действие «салам» уходило в тему 11 (акча салуу), объект «интернетим» —
#: в тему 3, и правило объявляло запрос противоречивым (0.71 -> отказ
#: 0.29, четыре теста живого диалога). Омонимия приветствия и глагола
#: ровно того же рода, что «эсеп» (счёт абонента и счёт в игре).
ACTION_WORDS: frozenset[str] = frozenset("""
кошуу кошом салуу
""".split())


def is_action(term: tuple[str, ...] | str) -> bool:
    """Называет ли слово операцию, а не предмет."""
    variants = (term,) if isinstance(term, str) else term
    return any(variant in ACTION_WORDS or variant.startswith(ACTION_PREFIXES)
               for variant in variants)


# --- Омонимы ---------------------------------------------------------------

#: Слова предметной области, у которых есть бытовое значение, и слова-
#: спутники, по которым видно именно бытовое.
#:
#: «Эсеп» — это и счёт абонента, и счёт в игре; русское «счёт» ровно так же.
#: Порогом это не лечится: «Футболдун эсеби кандай?» получало тему «баланс»
#: с уверенностью 0.47, а настоящие вопросы про баланс живут и ниже неё
#: (0.41). Лечится предметно: рядом со спутником («футбол», «матч», «оюн»)
#: слово означает игру, а не счёт абонента, и подтверждать тему не может.
#:
#: Похожесть строк при этом не меняется — меняется только право слова
#: подтверждать тему. Поэтому вопрос уходит в отказ с тремя кнопками,
#: а не в неверный ответ, и законный вопрос про счёт абонента («эсепке
#: акча салуу») не теряет ничего: спутника в нём нет.
#:
#: Правило наполнения жёсткое, иначе список превратится в чёрный список
#: внецелевых тем, то есть в память о размеченных строках: спутником может
#: быть только слово, которого в базе оператора нет вовсе. Это проверяется
#: тестом. «Команда» в спутники не попала именно поэтому — абонент может
#: спросить про USSD-команду.
HOMONYM_CONTEXT: tuple[tuple[tuple[str, ...], tuple[str, ...]], ...] = (
    # счёт абонента против счёта в игре (ky «эсеп/эсеб», ru «счет»)
    (("эсеп", "эсеб", "счет"),
     ("футбол", "матч", "оюн", "игр", "гол", "тайм", "чемпионат")),
)


def _foreign_homonym(term: tuple[str, ...], terms: list[tuple[str, ...]]) -> bool:
    """Стоит ли рядом с этим словом спутник его бытового значения."""
    for ambiguous, context in HOMONYM_CONTEXT:
        if not any(variant.startswith(ambiguous) for variant in term):
            continue
        if any(variant.startswith(context)
               for other in terms for variant in other):
            return True
    return False


def distinctive_terms(text: str) -> list[tuple[str, ...]]:
    """Слова запроса, которыми вообще можно различать темы.

    Из терминов запроса выброшены служебные слова, общие корни и омонимы,
    стоящие рядом со спутником бытового значения. То, что осталось, и есть
    содержание вопроса: «как купить симку» -> «симку». Пустой список
    означает, что вопрос не содержит ни одного слова, способного выбрать
    тему, — такой вопрос честнее не относить ни к одной.
    """
    terms = [term for term in content_terms(text) if not is_generic(term)]
    return [term for term in terms if not _foreign_homonym(term, terms)]


def content_text(text: str, expand_latin: bool = True) -> str:
    """Свёрнутый текст без служебных слов.

    Если после чистки не осталось ничего (вопрос состоял из одних
    служебных слов), возвращается пустая строка: поиску нечего искать,
    и честный ответ — «тема не найдена».
    """
    if expand_latin:
        terms = content_terms(text)
        return " ".join(" ".join(term) for term in terms)
    return " ".join(word for word in fold(text, expand_latin=False).split()
                    if word not in STOPWORDS)


