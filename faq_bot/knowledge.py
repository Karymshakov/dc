# --- Поисковая нормализация ------------------------------------------------

#: Свёртка кыргызских букв: «көрөм» и «korom» должны делить n-граммы.
_FOLD_MAP = str.maketrans({
    "ё": "е", "ө": "о", "ү": "у", "ң": "н", "һ": "х", "і": "и", "ї": "и",
})

#: Транслитерация кыргызской латиницы. Диграфы идут первыми.
_TRANSLIT_PAIRS: tuple[tuple[str, str], ...] = (
    ("sch", "щ"), ("sh", "ш"), ("ch", "ч"), ("zh", "ж"), ("kh", "х"),
    ("ts", "ц"), ("ya", "я"), ("yu", "ю"), ("yo", "е"), ("ye", "е"),
    ("ng", "нг"), ("a", "а"), ("b", "б"), ("c", "ц"), ("d", "д"),
    ("e", "е"), ("f", "ф"), ("g", "г"), ("h", "х"), ("i", "и"),
    ("j", "ж"), ("k", "к"), ("l", "л"), ("m", "м"), ("n", "н"),
    ("o", "о"), ("p", "п"), ("q", "к"), ("r", "р"), ("s", "с"),
    ("t", "т"), ("u", "у"), ("v", "в"), ("w", "в"), ("x", "кс"),
    ("y", "ы"), ("z", "з"),
)

_TOKEN_RE = re.compile(r"[0-9a-zа-яёөүңһі*#]+")
_CYRILLIC_RE = re.compile(r"[а-яёөүңһі]")


def transliterate(text: str) -> str:
    """Кыргызская латиница в кириллицу: «korom» -> «кором».

    Точность здесь не нужна: результат идёт в посимвольное сравнение,
    где важно общее начало слова, а не орфография.
    """
    result = text.lower()
    for latin, cyrillic in _TRANSLIT_PAIRS:
        result = result.replace(latin, cyrillic)
    return result


def _external_transliterate(text: str) -> str | None:
    """Транслитерация из faq_bot.normalize, если тот модуль уже написан.

    Модуль пишет другой участник бригады, и на момент написания поиска
    его может не быть. Поиск обязан работать в обоих случаях.
    """
    try:
        from faq_bot import normalize as external
    except Exception:  # pragma: no cover - модуль ещё не написан
        return None
    for name in ("transliterate", "translit", "latin_to_cyrillic",
                 "translit_to_cyrillic"):
        function = getattr(external, name, None)
        if callable(function):
            try:
                value = function(text)
            except Exception:  # pragma: no cover - чужой код, не падаем
                return None
            if isinstance(value, str) and value:
                return value
    return None


def fold(text: str, expand_latin: bool = True) -> str:
    """Нормализация ради сравнения строк.

    Нижний регистр, выброс пунктуации (кроме «*» и «#» ради *100# и *145*),
    свёртка ө/ү/ң. В запросе слово целиком на латинице добавляется дважды —
    как есть и в кириллице, — чтобы «apn» нашёл «APN», а «Balansymdy» нашёл
    «баланс». В индексе раскрытие выключено: транслитерация служебных
    латинских слов базы («internet.inai.example») давала ложные совпадения.
    """
    if not text:
        return ""
    pieces: list[str] = []
    for token in _TOKEN_RE.findall(text.lower()):
        pieces.append(token)
        if (expand_latin and not _CYRILLIC_RE.search(token)
                and any(ch.isalpha() for ch in token)):
            converted = _external_transliterate(token) or transliterate(token)
            if converted != token:
                pieces.append(converted)
    return " ".join(pieces).translate(_FOLD_MAP)


def tokens(text: str) -> list[str]:
    """Токены свёрнутого текста для токенных методов поиска."""
    return fold(text).split()


def query_terms(text: str) -> list[tuple[str, ...]]:
    """Термины запроса: латинское слово и его кириллица — один термин.

    Токенному методу важно, сколько СЛОВ запроса нашлось. Если «korom»
    и «кором» считать двумя словами, то кыргызская латиница автоматически
    теряет половину покрытия. Поэтому варианты написания одного слова
    отдаются вместе, а метод берёт по ним максимум.
    """
    if not text:
        return []
    terms: list[tuple[str, ...]] = []
    for token in _TOKEN_RE.findall(text.lower()):
        variants = [token]
        if not _CYRILLIC_RE.search(token) and any(ch.isalpha() for ch in token):
            converted = _external_transliterate(token) or transliterate(token)
            if converted != token:
                variants.append(converted)
        folded = tuple(dict.fromkeys(
            variant.translate(_FOLD_MAP) for variant in variants))
        if folded and folded not in terms:
            terms.append(folded)
    return terms


